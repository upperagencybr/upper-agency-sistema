create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  subscription_status text not null default 'ativo',
  system_name text not null default 'Upper Agency Sistema',
  lang text not null default 'pt',
  theme text not null default 'dark',
  font text not null default 'inter',
  monthly_goal numeric not null default 8000,
  created_at timestamptz not null default now()
);
grant select, update on public.profiles to authenticated;
grant all on public.profiles to service_role;
alter table public.profiles enable row level security;
create policy "own profile read" on public.profiles for select to authenticated using (id = auth.uid());
create policy "own profile update" on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid());
create or replace function public.protect_subscription() returns trigger language plpgsql set search_path=public as $$
begin
  if current_user = 'authenticated' and new.subscription_status is distinct from old.subscription_status then
    new.subscription_status := old.subscription_status;
  end if;
  return new;
end $$;
create trigger profiles_protect_sub before update on public.profiles for each row execute function public.protect_subscription();

