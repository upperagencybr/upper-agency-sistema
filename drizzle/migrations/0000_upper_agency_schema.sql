create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path=public as $$
declare first_user boolean;
begin
  select not exists (select 1 from public.profiles) into first_user;
  insert into public.profiles (id, email) values (new.id, new.email);
  if first_user then
    update public.companies set user_id = new.id where user_id is null;
    update public.clients set user_id = new.id where user_id is null;
    update public.transactions set user_id = new.id where user_id is null;
    update public.crm_leads set user_id = new.id where user_id is null;
    update public.accounting_tasks set user_id = new.id where user_id is null;
    update public.inbox_reads set user_id = new.id where user_id is null;
  end if;
  return new;
end $$;
revoke execute on function public.handle_new_user() from public, anon, authenticated;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

