-- helpers
create or replace function public.role_rank(r text) returns int language sql immutable as $$
  select case r when 'admin' then 3 when 'editor' then 2 when 'viewer' then 1 else 0 end $$;

-- caller's role in a company: owner/admin/editor/viewer/null
create or replace function public.company_role(_company_id bigint) returns text
language sql stable security definer set search_path = public as $$
  select case
    when exists (select 1 from companies c where c.id = _company_id and c.user_id = auth.uid()) then 'owner'
    else (select m.role from company_members m where m.company_id = _company_id and m.user_id = auth.uid() limit 1)
  end $$;

-- caller's best member role over owner's data, for a company name (null = any company) and a tab
create or replace function public.member_role(_owner uuid, _company text, _tab text) returns text
language sql stable security definer set search_path = public as $$
  select m.role from company_members m join companies c on c.id = m.company_id
  where m.user_id = auth.uid() and c.user_id = _owner
    and (_company is null or c.name = _company)
    and (m.kind = 'socio' or _tab = any(m.tabs))
  order by public.role_rank(m.role) desc limit 1 $$;

-- do two users share any company (owner<->member or member<->member)
create or replace function public.shares_workspace(_other uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select _other = auth.uid() or exists (
    select 1 from companies c
    left join company_members m1 on m1.company_id = c.id
    left join company_members m2 on m2.company_id = c.id
    where (c.user_id = auth.uid() and m1.user_id = _other)
       or (c.user_id = _other and m1.user_id = auth.uid())
       or (m1.user_id = auth.uid() and m2.user_id = _other)
  ) $$;

-- owner of the workspace a new row belongs to
create or replace function public.row_owner(_company text) returns uuid
language sql stable security definer set search_path = public as $$
  select coalesce(
    (select c.user_id from companies c join company_members m on m.company_id = c.id
      where _company is not null and c.name = _company and m.user_id = auth.uid() and m.role in ('editor','admin') limit 1),
    (select auth.uid() where exists (select 1 from companies where user_id = auth.uid())),
    (select c.user_id from companies c join company_members m on m.company_id = c.id
      where m.user_id = auth.uid() and m.role in ('editor','admin') order by public.role_rank(m.role) desc limit 1),
    auth.uid()) $$;

create or replace function public.assign_row_owner() returns trigger
language plpgsql security definer set search_path = public as $$
declare comp text;
begin
  if auth.uid() is null then return new; end if;
  begin comp := (to_jsonb(new) ->> 'company'); exception when others then comp := null; end;
  new.user_id := public.row_owner(comp);
  return new;
end $$;

do $$ declare t text; begin
  foreach t in array array['clients','transactions','crm_leads','projects','mentoring_sessions','accounting_tasks','nexo_contents','tags'] loop
    execute format('create trigger %I_assign_owner before insert on public.%I for each row execute function public.assign_row_owner()', t, t);
  end loop;
end $$;

-- member policies (additive; "own rows" policies remain)
do $$ declare r record; begin
  for r in select * from (values
    ('clients','clientes',true),('transactions','financeiro',true),('crm_leads','crm',true),('projects','projetos',true),
    ('nexo_contents','conteudo',true),('mentoring_sessions','mentorados',false),('accounting_tasks','contabilidade',false)
  ) v(tbl, tab, has_company) loop
    declare comp text := case when r.has_company then 'company' else 'null' end;
    begin
      execute format('create policy "member read" on public.%I for select to authenticated using (public.member_role(user_id, %s, %L) is not null)', r.tbl, comp, r.tab);
      execute format('create policy "member insert" on public.%I for insert to authenticated with check (public.role_rank(public.member_role(user_id, %s, %L)) >= 2)', r.tbl, comp, r.tab);
      execute format('create policy "member update" on public.%I for update to authenticated using (public.role_rank(public.member_role(user_id, %s, %L)) >= 2) with check (public.role_rank(public.member_role(user_id, %s, %L)) >= 2)', r.tbl, comp, r.tab, comp, r.tab);
      execute format('create policy "member delete" on public.%I for delete to authenticated using (public.member_role(user_id, %s, %L) = ''admin'')', r.tbl, comp, r.tab);
    end;
  end loop;
end $$;

